import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { PGlite } from "@electric-sql/pglite";
import test from "node:test";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");

test("licensed-audio migration preserves existing provider rows and adds only the audio provider", async () => {
  const database = new PGlite();
  try {
    await database.exec(`
      create table public.prayer_music_items (
        id integer generated by default as identity primary key,
        title text not null,
        provider text not null check (provider in ('spotify', 'youtube')),
        provider_url text not null
      );
      insert into public.prayer_music_items(title,provider,provider_url) values
        ('Spotify example','spotify','https://open.spotify.com/track/example'),
        ('YouTube example','youtube','https://www.youtube.com/watch?v=example');
    `);
    const migration = await readFile(path.join(projectRoot, "supabase/migrations/202611010002_prayer_music_audio_provider.sql"), "utf8");
    await database.exec(migration);
    const existing = await database.query("select provider from public.prayer_music_items order by id");
    assert.deepEqual(existing.rows.map((row) => row.provider), ["spotify", "youtube"]);
    await database.exec("insert into public.prayer_music_items(title,provider,provider_url) values('Licensed recording','audio','https://media.example/prayer.mp3')");
    await assert.rejects(database.exec("insert into public.prayer_music_items(title,provider,provider_url) values('Unsupported','broadcast','https://media.example/prayer.mp3')"));
  } finally {
    await database.close();
  }
});
